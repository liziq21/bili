#!/usr/bin/env python3
"""Rebuild CHANGELOG.md from merged pull requests.

The file is derived state, not a hand-maintained document: every run rebuilds it
from git tags plus the GitHub pulls API, so a run that finds nothing new leaves
the file byte-identical. Editing the file by hand is therefore pointless — the
next run overwrites it.

Sections come from tags, not from a version bump commit:

* one `## vX.Y.Z - <tag date>` section per tag, holding the pull requests that
  landed after the previous tag and no later than this one;
* a leading `## [Unreleased]` section for pull requests newer than the newest tag.

The oldest tag absorbs everything merged before it, so no merged pull request is
ever dropped just because it predates the first release.

Pull requests are bucketed by their `c:` label when the Linear/GitHub label sync
has attached one, and otherwise by the conventional-commit prefix (or the agent
emoji prefix) in the title. Anything unrecognised lands in `Other` rather than
being dropped.

Usage:
    python3 tool/generate_changelog.py [--output CHANGELOG.md] [--repo OWNER/NAME]

Reads GH_TOKEN (or GITHUB_TOKEN) for the API call. Only writes the output file
when the generated content differs from what is already there.
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import os
import re
import subprocess
import sys
import urllib.error
import urllib.request
from typing import Any, Iterable, Sequence

# Section order in the rendered document. Order here is the order on disk.
SECTIONS: tuple[str, ...] = (
    "Added",
    "Fixed",
    "Changed",
    "Documentation",
    "Tests",
    "Maintenance",
    "Other",
)

# Pull requests carrying these labels are left out of the document. The
# changelog workflow runs on every merge to main, so a regenerated changelog
# pull request is itself a merged pull request: listing it makes every merged
# changelog pull request produce the next one, forever.
EXCLUDED_LABELS: tuple[str, ...] = ("ci-generated",)

# `c:` labels synced from Linear take precedence over the title heuristics.
LABEL_SECTIONS: dict[str, str] = {
    "c: feature": "Added",
    "c: tech-debt": "Fixed",
    "c: test-gap": "Fixed",
    "c: process": "Fixed",
    "c: decision": "Other",
    "c: infra": "Maintenance",
}

# Title prefixes, checked in order. Anchored so `refactor(` is not matched by a
# mid-title mention of the word.
TITLE_SECTIONS: tuple[tuple[str, str], ...] = (
    ("feat(", "Added"),
    ("feat:", "Added"),
    ("fix(", "Fixed"),
    ("fix:", "Fixed"),
    ("Fix ", "Fixed"),
    ("docs(", "Documentation"),
    ("docs:", "Documentation"),
    ("test(", "Tests"),
    ("test:", "Tests"),
    ("refactor(", "Changed"),
    ("refactor:", "Changed"),
    ("design(", "Changed"),
    ("design:", "Changed"),
    ("style(", "Changed"),
    ("style:", "Changed"),
    ("perf(", "Changed"),
    ("perf:", "Changed"),
    ("chore(", "Maintenance"),
    ("chore:", "Maintenance"),
    ("ci(", "Maintenance"),
    ("ci:", "Maintenance"),
    ("Add ", "Added"),
    ("Implement ", "Added"),
    # Agent lanes: Bolt is performance work on existing widgets, Palette is UI
    # polish and accessibility, Sentinel is security/robustness. None of them
    # add a user-facing capability on their own, so they are `Changed` / `Fixed`
    # rather than `Added`.
    ("⚡ Bolt:", "Changed"),
    ("🎨 Palette:", "Changed"),
    ("🛡️ Sentinel:", "Fixed"),
)

# Keyword rules, checked in order after the prefix rules. This repository has a
# large share of Chinese pull request titles with no conventional-commit prefix,
# so without these they would all collapse into `Other`. Multi-character
# keywords only: a single character such as 修 also matches 修改 ("modify"),
# which is not necessarily a fix.
KEYWORD_SECTIONS: tuple[tuple[str, str], ...] = (
    ("修复", "Fixed"),
    ("修正", "Fixed"),
    ("修掉", "Fixed"),
    ("新增", "Added"),
    ("添加", "Added"),
    ("实现", "Added"),
    ("接入", "Added"),
    ("重构", "Changed"),
    ("优化", "Changed"),
    ("收敛", "Changed"),
    ("调整", "Changed"),
    ("文档", "Documentation"),
    ("规范", "Documentation"),
    ("测试", "Tests"),
    ("校验", "Tests"),
    ("更新", "Maintenance"),
    ("维护", "Maintenance"),
    ("清理", "Maintenance"),
    ("迁移", "Maintenance"),
    ("升级", "Maintenance"),
    ("依赖", "Maintenance"),
)

# Dependency bumps have no conventional prefix on this repository.
BUMP_PATTERNS: tuple[str, ...] = (
    r"^Bump ",
    r"^Pin dependencies",
    r"^Update \S+ to ",
    r"^Update github/",
    r"^Update plugin ",
    r"^Update Gradle",
    r"^Update Flutter",
    r"^deps:",
    r"^up$",
)

UNRELEASED = "Unreleased"

PREAMBLE = (
    "# Changelog\n"
    "\n"
    "Generated by `tool/generate_changelog.py` from pull requests merged into\n"
    "`main`. The file is rebuilt from git tags and the GitHub API on every run,\n"
    "so hand edits do not survive; change the generator instead.\n"
)


def parse_iso(value: str) -> dt.datetime:
    """Parse an ISO-8601 timestamp, tolerating the `Z` suffix Python <3.11 rejects."""
    text = value.strip()
    if text.endswith("Z"):
        text = text[:-1] + "+00:00"
    parsed = dt.datetime.fromisoformat(text)
    if parsed.tzinfo is None:
        parsed = parsed.replace(tzinfo=dt.timezone.utc)
    return parsed.astimezone(dt.timezone.utc)


def categorize(title: str, labels: Iterable[str]) -> str:
    """Return the section a pull request belongs to."""
    label_names = {label.strip() for label in labels}
    for label, section in LABEL_SECTIONS.items():
        if label in label_names:
            return section
    lowered = title.strip()
    for prefix, section in TITLE_SECTIONS:
        if lowered.startswith(prefix):
            return section
    for keyword, section in KEYWORD_SECTIONS:
        if keyword in lowered:
            return section
    for pattern in BUMP_PATTERNS:
        if re.search(pattern, lowered):
            return "Maintenance"
    return "Other"


def render_entry(title: str, number: int) -> str:
    return f"- {title} (#{number})"


def render_entries(entries: Sequence[dict[str, Any]]) -> str:
    """Render one `###` block per non-empty section, in SECTIONS order."""
    buckets: dict[str, list[str]] = {name: [] for name in SECTIONS}
    for entry in entries:
        buckets[entry["section"]].append(
            render_entry(entry["title"], entry["number"])
        )
    blocks = []
    for name in SECTIONS:
        lines = buckets[name]
        if not lines:
            continue
        blocks.append("\n".join([f"### {name}", *lines]))
    if not blocks:
        return ""
    return "\n\n".join(blocks) + "\n"


def section_header(tag: str | None, tag_date: dt.datetime | None) -> str:
    if tag is None:
        return f"## [{UNRELEASED}]"
    assert tag_date is not None
    return f"## {tag} - {tag_date.date().isoformat()}"


def build_document(
    tags: Sequence[tuple[str, dt.datetime]],
    pull_requests: Sequence[dict[str, Any]],
) -> str:
    """Render the whole file from tags (newest first) and merged pull requests.

    `tags` must be ordered newest first; each entry is the tag name and the
    commit date it points at. `pull_requests` need `number`, `title`, `labels`
    and a `merged_at` datetime; ordering of the input does not matter.
    """
    merged = sorted(
        (dict(pr, merged_at=pr["merged_at"]) for pr in pull_requests),
        key=lambda pr: (pr["merged_at"], pr["number"]),
    )

    # A merged pull request ships in the *earliest* release tagged at or after
    # its merge date, so walk tags oldest-first and let the first match claim it.
    # A pull request merged before the oldest tag therefore lands in that tag
    # rather than being dropped.
    ordered_tags = list(tags)
    by_tag: dict[str | None, list[dict[str, Any]]] = {tag: [] for tag, _ in ordered_tags}
    by_tag.setdefault(None, [])
    for pr in merged:
        for tag, tag_date in reversed(ordered_tags):
            if pr["merged_at"] <= tag_date:
                by_tag[tag].append(pr)
                break
        else:
            by_tag[None].append(pr)

    parts = [PREAMBLE]
    # Keep a Changelog order: unreleased work first, then releases newest first.
    sections: list[tuple[str | None, dt.datetime | None]] = [(None, None)]
    sections.extend(ordered_tags)
    for tag, tag_date in sections:
        entries = [
            {
                "title": pr["title"],
                "number": pr["number"],
                "section": categorize(pr["title"], pr.get("labels", [])),
            }
            for pr in by_tag.get(tag, [])
        ]
        if not entries:
            continue
        body = render_entries(entries)
        if not body:
            continue
        parts.append(f"{section_header(tag, tag_date)}\n\n{body.rstrip()}\n")
    return "\n\n".join(parts)


def run_git(*args: str) -> str:
    result = subprocess.run(
        ["git", *args], check=True, capture_output=True, text=True
    )
    return result.stdout.strip()


def collect_tags(repo_root: str) -> list[tuple[str, dt.datetime]]:
    """Return `(tag, commit date)` newest first, newest by tag version order."""
    raw = run_git("-C", repo_root, "tag", "--sort=-v:refname")
    tags: list[tuple[str, dt.datetime]] = []
    for line in raw.splitlines():
        tag = line.strip()
        if not tag:
            continue
        stamp = run_git("-C", repo_root, "log", "-1", "--format=%cI", tag)
        tags.append((tag, parse_iso(stamp)))
    return tags


def parse_repo_slug(value: str) -> str:
    """Accept `owner/name`, an https remote URL, or an ssh remote URL."""
    text = value.strip()
    match = re.search(r"github\.com[:/]+([^/]+)/([^/\s]+?)(?:\.git)?$", text)
    if match:
        return f"{match.group(1)}/{match.group(2)}"
    if re.fullmatch(r"[\w.-]+/[\w.-]+", text):
        return text
    raise ValueError(f"cannot read an owner/name pair from {value!r}")


def fetch_merged_pull_requests(
    repo_slug: str, token: str, base: str = "main"
) -> list[dict[str, Any]]:
    """Return merged pull requests targeting `base`, oldest merge first."""
    url = (
        f"https://api.github.com/repos/{repo_slug}/pulls"
        f"?state=closed&per_page=100&page={'{page}'}&base={base}"
    )
    collected: list[dict[str, Any]] = []
    page = 1
    while True:
        request = urllib.request.Request(
            url.format(page=page),
            headers={
                "Authorization": f"Bearer {token}",
                "Accept": "application/vnd.github+json",
                "X-GitHub-Api-Version": "2022-11-28",
            },
        )
        try:
            with urllib.request.urlopen(request) as response:
                batch = json.load(response)
        except urllib.error.URLError as error:
            raise SystemExit(f"GitHub API request failed: {error}") from error
        if not isinstance(batch, list):
            raise SystemExit("GitHub API returned a non-list payload")
        if not batch:
            break
        for item in batch:
            merged_at = item.get("merged_at")
            if not merged_at:
                continue
            if (item.get("base") or {}).get("ref") != base:
                continue
            labels = [
                (label or {}).get("name", "") for label in item.get("labels") or []
            ]
            if any(name in EXCLUDED_LABELS for name in labels):
                continue
            collected.append(
                {
                    "number": item["number"],
                    "title": (item.get("title") or "").strip(),
                    "labels": labels,
                    "merged_at": parse_iso(merged_at),
                }
            )
        if len(batch) < 100:
            break
        page += 1
    return collected


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", default="CHANGELOG.md")
    parser.add_argument("--repo", default=None, help="owner/name; default: origin remote")
    parser.add_argument("--base", default="main")
    parser.add_argument("--repo-root", default=".")
    args = parser.parse_args(argv)

    token = os.environ.get("GH_TOKEN") or os.environ.get("GITHUB_TOKEN")
    if not token:
        print("error: set GH_TOKEN or GITHUB_TOKEN", file=sys.stderr)
        return 1

    if args.repo:
        repo_slug = parse_repo_slug(args.repo)
    else:
        try:
            repo_slug = parse_repo_slug(run_git("-C", args.repo_root, "remote", "get-url", "origin"))
        except (subprocess.CalledProcessError, ValueError) as error:
            print(f"error: cannot determine repository: {error}", file=sys.stderr)
            return 1

    tags = collect_tags(args.repo_root)
    pull_requests = fetch_merged_pull_requests(repo_slug, token, args.base)
    document = build_document(tags, pull_requests)

    output_path = os.path.join(args.repo_root, args.output) if args.repo_root != "." else args.output
    existing = None
    if os.path.exists(output_path):
        with open(output_path, encoding="utf-8") as handle:
            existing = handle.read()
    if existing == document:
        print(f"{args.output} is up to date ({len(pull_requests)} merged pull requests)")
        return 0
    with open(output_path, "w", encoding="utf-8") as handle:
        handle.write(document)
    print(
        f"wrote {args.output} ({len(pull_requests)} merged pull requests, "
        f"{len(tags)} tag(s))"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
